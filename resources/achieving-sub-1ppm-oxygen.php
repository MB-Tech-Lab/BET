            <h3>1. Oxygen Removal via Copper Catalyst</h3>
            <p>
              Oxygen cannot be simply filtered out mechanically. It must be chemically bound. We utilize a highly active, porous copper catalyst bed. When gas passes through the bed at room temperature, oxygen molecules react with the copper:
            </p>
            <p class="text-center"><strong>$2\text{Cu} + \text{O}_2 \rightarrow 2\text{CuO}$</strong></p>
            <p>
              This reaction converts free oxygen gas into solid Copper Oxide ($CuO$), trapping it inside the purification column. The copper catalyst can absorb oxygen down to fractional ppb levels.
            </p>

            <h3>2. Moisture Removal via Synthetic Zeolite (Molecular Sieve)</h3>
            <p>
              Moisture is trapped using a high-grade synthetic <strong>molecular sieve</strong> (typically 3A, 4A, or 13X zeolite). Zeolites are crystalline aluminosilicates with precise nanometer-sized pores. 
            </p>
            <p>
              Water molecules enter the pores and are strongly adsorbed by physical electrostatic forces, trapping the moisture. The molecular sieve continues to adsorb water until it reaches thermodynamic equilibrium.
            </p>

            <h3>3. Regeneration Cycle Dynamics</h3>
            <p>
              When the catalyst bed and molecular sieve become saturated, the system's purification efficiency drops. The system is then regenerated by a PLC program:
            </p>
            <ul>
              <li><strong>Heating Phase:</strong> The column is isolated and heated to 200°C–250°C.</li>
              <li><strong>Reducing Gas Purge:</strong> A gas mixture (95% Argon/Nitrogen + 5% Hydrogen) is introduced. The Hydrogen ($H_2$) reacts with Copper Oxide to release water vapor, reducing the copper back to its active metal state: <strong>$\text{CuO} + \text{H}_2 \rightarrow \text{Cu} + \text{H}_2\text{O}$</strong>.</li>
              <li><strong>Cooling Phase:</strong> Water vapor is vented, the column is cooled down, evacuated under vacuum, and put back online.</li>
            </ul>
